"""Generate the reference pages of the manual from the code.

    uv --directory backend run python ../scripts/gen_manual.py           # write
    uv --directory backend run python ../scripts/gen_manual.py --check   # fail when stale

* ``manual/configuration.md`` from ``deploy/production/heracles.example.yaml`` (one section per
  ``# --- name ---`` block: its leading comments as text, the block as YAML).
* ``manual/plugins.md`` from the installed plugins (entry points ``heracles.plugins``): name,
  version, whether it is in the core profile, the LDAP classes the directory must define, and
  the first paragraph of the plugin module's docstring.
"""

from __future__ import annotations

import argparse
import importlib
import re
import sys
from importlib.metadata import entry_points
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLE = ROOT / "deploy" / "production" / "heracles.example.yaml"
MANUAL = ROOT / "manual"
NOTICE = "<!-- Generated by scripts/gen_manual.py: edit the sources, not this file. -->\n\n"
SECTION = re.compile(r"^# --- (?P<title>.+?) -+\s*$")


def configuration() -> str:
    lines = EXAMPLE.read_text(encoding="utf-8").splitlines()
    preamble: list[str] = []
    sections: list[tuple[str, list[str]]] = []
    for line in lines:
        match = SECTION.match(line)
        if match:
            sections.append((match["title"].strip(), []))
        elif sections:
            sections[-1][1].append(line)
        else:
            preamble.append(line)
    out = [
        NOTICE,
        "# Configuration reference\n\n",
        "The configuration file is `$HERACLES_CONFIG` (or `--config PATH`). Every setting is shown\n",
        "below with its comment, as in [`deploy/production/heracles.example.yaml`]",
        "(../deploy/production/heracles.example.yaml); commented lines are optional settings with\n",
        "their default or an example value.\n\n",
    ]
    intro = [p.lstrip("# ").rstrip() for p in preamble if p.startswith("#")]
    if intro:
        out.append(" ".join(x for x in intro if x) + "\n\n")
    for title, body in sections:
        while body and not body[-1].strip():
            body.pop()
        while body and not body[0].strip():
            body.pop(0)
        out.append(f"## {title[:1].upper()}{title[1:]}\n\n```yaml\n")
        out.append("\n".join(body) + "\n```\n\n")
    return "".join(out).rstrip() + "\n"


def _first_paragraph(doc: str | None) -> str:
    if not doc:
        return ""
    text = doc.strip().split("\n\n", 1)[0]
    return " ".join(text.split())


def plugins() -> str:
    from heracles.objects.activation import CORE_PROFILE

    rows: list[tuple[str, str, str, str, str]] = []
    for point in sorted(entry_points(group="heracles.plugins"), key=lambda p: p.name):
        plugin = point.load()()
        module = importlib.import_module(point.module)
        classes = ", ".join(f"`{c}`" for c in plugin.required_object_classes) or "—"
        rows.append(
            (
                plugin.name,
                plugin.version,
                "yes" if plugin.name in CORE_PROFILE else "",
                classes,
                _first_paragraph(module.__doc__),
            )
        )
    out = [
        NOTICE,
        "# Plugins reference\n\n",
        "Plugins add object types, tabs, tasks and API routes. A plugin is active when it is\n",
        "listed in `plugins.enabled` (or switched on in the console under *Plugins*) **and** the\n",
        "directory schema defines the object classes it needs. Without `plugins.enabled`, the\n",
        f"core profile is on: {', '.join(f'`{p}`' for p in CORE_PROFILE)}.\n\n",
        "| Plugin | Version | Core | Needs the classes |\n| --- | --- | --- | --- |\n",
    ]
    for name, version, core, classes, _summary in rows:
        out.append(f"| [`{name}`](#{name}) | {version} | {core} | {classes} |\n")
    out.append("\n")
    for name, _version, _core, _classes, summary in rows:
        out.append(f"## {name}\n\n{summary or 'No description.'}\n\n")
    return "".join(out).rstrip() + "\n"


PAGES = {"configuration.md": configuration, "plugins.md": plugins}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the manual reference pages")
    parser.add_argument("--check", action="store_true", help="fail when a page is out of date")
    args = parser.parse_args(argv)
    stale: list[str] = []
    for name, build in PAGES.items():
        path = MANUAL / name
        text = build()
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print(
            "manual out of date: " + ", ".join(stale) + " (run scripts/gen_manual.py)",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
