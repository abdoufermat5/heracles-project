import {
  Box,
  Briefcase,
  Building,
  Building2,
  Calendar,
  Eye,
  FileKey,
  FileText,
  Globe,
  Key,
  KeyRound,
  Mail,
  Monitor,
  Network,
  Phone,
  Printer,
  Server,
  Settings,
  Shield,
  ShieldCheck,
  Smartphone,
  SquareTerminal,
  User,
  Users,
  UsersRound,
  Workflow,
  type LucideIcon,
} from 'lucide-react'

/** Icon names used by object types (server-provided) → icons. Unknown names get a box. */
const map: Record<string, LucideIcon> = {
  user: User,
  users: Users,
  'users-round': UsersRound,
  shield: Shield,
  'shield-check': ShieldCheck,
  building: Building,
  'building-2': Building2,
  briefcase: Briefcase,
  calendar: Calendar,
  eye: Eye,
  file: FileText,
  'file-key': FileKey,
  globe: Globe,
  server: Server,
  monitor: Monitor,
  printer: Printer,
  phone: Phone,
  smartphone: Smartphone,
  terminal: SquareTerminal,
  mail: Mail,
  network: Network,
  key: Key,
  'key-round': KeyRound,
  workflow: Workflow,
  settings: Settings,
}

export function TypeIcon({ name, className }: { name: string; className?: string }) {
  const Icon = map[name] ?? Box
  return <Icon className={className} aria-hidden />
}
